#!/usr/bin/env bash
# Проверка согласованности каркаса — запускать после обновления и перед раздачей.
#
# ЗАЧЕМ. 01.09.2026 в каркасе нашли два противоречия, прожившие с первого дня:
#   • документы велели владельцу писать настройки в `config/lab.yaml`, а помощник читал
#     `config/lab.local.yaml` — имена уходили туда, где их никто не читает, и стирались
#     при первом же обновлении;
#   • `ОБНОВЛЕНИЕ.md` запрещал править `coordinators/`, а `docs/АРХИТЕКТУРА.md` велел
#     копировать туда шаблон — то есть ровно то, ради чего каркас и отдают.
#
# Оба появились не от небрежности: правка v1.0.1 переименовала файл в КОДЕ и не дошла до
# документов. Человек этого не увидит — файлы разные, каждый по отдельности верен.
# Поэтому проверка машинная и стоит НА ПУТИ обновления, а не в чьей-то памяти.
#
# Коды: 0 согласовано · 1 противоречие · 2 не смог проверить (файлов нет)
#
# 🧪 У этой проверки есть СТЕНД: scripts/стенд-проверки-каркаса.sh — 19 случаев в обе
#    стороны. Меняешь что-то здесь — сначала допиши туда случай, который на правке
#    КРАСНЕЕТ, потом чини. Проверка, которую нельзя уронить, ничего не доказывает.

set -u
cd "$(dirname "$0")/.." || exit 2
FAIL=0
RAN=0
SKIPPED=0
WARN=0
ok()   { echo "  ✅ $1"; RAN=$((RAN+1)); }
bad()  { echo "  ❌ $1"; FAIL=$((FAIL+1)); RAN=$((RAN+1)); }
# ⚠️ НЕ проверено — это НЕ «в порядке». Зелёный вердикт после пропуска запрещён:
#    ноль найденного не различает «держит» и «не смог посмотреть».
skip() { echo "  ⚠️  НЕ ПРОВЕРЕНО — $1"; SKIPPED=$((SKIPPED+1)); }
# ❗ Проверено, найдено, но это НЕ ошибка сборки каркаса: состояние вот этой машины.
#    Отдельный уровень нужен затем, чтобы владелец, поправивший файл каркаса, не
#    получал «❌ противоречие» и не шёл жаловаться команде на свою же правку.
warn() { echo "  ❗ $1"; WARN=$((WARN+1)); }

# ⛔ САМОКОНТРОЛЬ ПЕРЕД ЛЮБЫМ ВЫВОДОМ. Системный grep на macOS БЕЗ UTF-8-локали не
#    сворачивает кириллический регистр: `grep -i 'впиши'` НЕ находит «Впишите» (проверено
#    01.09: 0 совпадений без локали, 1 — с LC_ALL). Первая версия этой проверки на том и
#    ослепла: контроль «документ велит писать в обновляемый файл» молча не сработал.
#    Поэтому ниже везде ЯВНЫЕ классы вида [Вв], а не -i, — они не зависят от окружения
#    того, кто запускает. А эта проба ловит случай, если инструмент сломан как-то иначе.
if [ "$(printf 'Впишите\n' | grep -c '[Вв]пиши')" != "1" ]; then
  echo "❌ проверка СЛЕПА на кириллице (grep не нашёл заведомое) — вердикт недействителен"
  exit 2
fi

echo "=== Согласованность каркаса ==="

# Схема настроек тоже обязательна: на ней стоят проверки 5, 6 и 7. Без неё они
# зеленели ВХОЛОСТУЮ, а вердикт рапортовал полный объём (найдено встречной проверкой 03.09).
for f in CLAUDE.md .gitignore ОБНОВЛЕНИЕ.md docs/АРХИТЕКТУРА.md ДОБРО_ПОЖАЛОВАТЬ.md config/lab.yaml.example; do
  [ -f "$f" ] || { echo "  ⚠️  нет $f — проверять нечего"; exit 2; }
done

# 1. Файл, который ЧИТАЕТ помощник, обязан быть тем, который ЗАЩИЩАЕТ .gitignore.
#    Иначе настройки владельца либо не читаются, либо затираются обновлением.
READS=$(grep -o 'config/lab[a-z.]*\.yaml' CLAUDE.md | sort -u | head -1)
IGNORED=$(grep -o 'config/lab[a-z.]*\.yaml' .gitignore | sort -u | head -1)
if [ -z "$READS" ] || [ -z "$IGNORED" ]; then
  bad "не нашёл, какой конфиг читает помощник ($READS) или что защищает .gitignore ($IGNORED)"
elif [ "$READS" = "$IGNORED" ]; then
  ok "помощник читает $READS — и он же под защитой .gitignore"
else
  bad "помощник читает $READS, а .gitignore защищает $IGNORED — настройки владельца потеряются"
fi

# 2. Ни один документ не должен ВЕЛЕТЬ владельцу писать в файл, который обновляется.
#    Упоминание в пояснении («это заготовка, она обновляется») законно — ищем ПОВЕЛЕНИЕ.
TRACKED_CFG="config/lab.yaml"
VELIT=$(grep -rn "$TRACKED_CFG" --include='*.md' . 2>/dev/null \
        | grep -vE '[Зз]аготовк|[Оо]бновля|[Пп]ерезапис|не ваш|была неправа|стояло|НЕ в |а НЕ' \
        | grep -E '[Вв]пиши|[Зз]апиши|[Уу]каж[ие]|[Зз]аполни|[Вв]неси|ваши настройки|ваши имена' || true)
if [ -z "$VELIT" ]; then
  ok "ни один документ не велит писать в $TRACKED_CFG"
else
  bad "документ велит писать в обновляемый $TRACKED_CFG:"
  printf '%s\n' "$VELIT" | sed 's/^/       /'
fi

# 3. Про coordinators/ документы не должны говорить противоположное.
#    Ищем прямой запрет рядом с прямым указанием копировать шаблон.
# ⚠️ Цитата запрета в ПОЯСНЕНИИ — не запрет. Первая версия этой проверки покраснела на
#    собственном примечании «до 01.09 здесь стояло „не правьте“»: упоминание засчиталось
#    за употребление. Отсекаем цитаты (строки-выноски `>`) и ссылки на прошлое.
ZAPRET=$(grep -rn 'coordinators/' --include='*.md' . 2>/dev/null \
         | grep -E 'не правьте|не трогайте|нельзя править' \
         | grep -vE ':[0-9]+:>' \
         | grep -vE 'стояло|[Рр]аньше|до 01\.09|была неправа|[Пп]режде' || true)
VELENIE=$(grep -rn 'coordinators/_template' --include='*.md' . 2>/dev/null || true)
if [ -n "$ZAPRET" ] && [ -n "$VELENIE" ]; then
  bad "один документ запрещает править coordinators/, другой велит копировать туда шаблон:"
  printf '%s\n' "$ZAPRET"   | sed 's/^/       запрет:  /'
  printf '%s\n' "$VELENIE" | sed 's/^/       указание:/'
else
  ok "про coordinators/ документы не спорят"
fi

# 4. START_HERE обязан открыть разговор ПЕРВЫМ ходом.
#    Голое `exec claude` даёт пустой REPL, который молчит, — при том что человеку строкой
#    выше обещано «помощник представится и задаст вопросы» (найдено 01.09).
if grep -qE '^[[:space:]]*exec[[:space:]]+claude[[:space:]]*$' START_HERE.command; then
  bad "START_HERE открывает ПУСТОЙ разговор (голое 'exec claude') — помощник промолчит, хотя владельцу обещано, что он представится и задаст вопросы"
elif grep -qE '^[[:space:]]*exec[[:space:]]+claude[[:space:]]+' START_HERE.command; then
  ok "START_HERE передаёт первый запрос — разговор начинает помощник"
else
  bad "в START_HERE не найден запуск claude — проверить вручную"
fi

# 5. Наработки: если про них СПРАШИВАЮТ, им должно быть КУДА лечь и КТО их читает.
#    До 01.09 онбординг спрашивал «что уже есть на руках», а ответ никуда не сохранялся:
#    лаборатория заводилась с чистого листа у человека, у которого лист не чистый.
ASKS=$(grep -c '[Нн]аработк' CLAUDE.md || true)
HAS_FIELD=$(grep -c '^prior_work:' config/lab.yaml.example || true)
if [ "$ASKS" = "0" ]; then
  bad "онбординг не спрашивает про существующие наработки — владелец начнёт с нуля"
elif [ "$HAS_FIELD" = "0" ]; then
  bad "про наработки спрашивают, но в config/lab.yaml.example нет поля 'prior_work' — ответ пропадёт"
else
  ok "наработки: спрашиваются, есть поле в конфиге, помощник читает их при старте"
fi

# 6. Схема настроек должна быть ОДНА. Два одинаковых шаблона под разными именами —
#    это развилка, из которой вырос исходный дефект каркаса: документы показывали на
#    один файл, помощник читал другой. До 01.09 lab.yaml и lab.yaml.example были
#    побайтно равны (1472 б); теперь lab.yaml — заглушка-пояснение, а схема одна.
if [ -f config/lab.yaml ] && [ -f config/lab.yaml.example ] \
   && cmp -s config/lab.yaml config/lab.yaml.example; then
  bad "config/lab.yaml и config/lab.yaml.example ПОБАЙТНО ОДИНАКОВЫ — две схемы под разными именами, из этой развилки уже вырастал дефект"
else
  ok "схема настроек одна (lab.yaml.example); lab.yaml — только путь переноса со старой версии"
fi

# 7. Ключи схемы — ОДНИМ алфавитом. Находка dev-coord 01.09: я добавила поле
#    кириллицей в файл, где остальные семь латиницей. Живого дефекта не было
#    (мигрировать нечего), но обвязка вокруг схемы писана под латиницу: образец
#    миграции в START_HERE — '^[a-z_]+:', и кириллический ключ он не видит МОЛЧА.
#    Сегодня класс «кириллица ломает поиск» ловился четырежды, дважды у самого
#    автора сторожа. Смешанный алфавит в схеме — заготовленная восьмая ловушка.
# ⚠️ Ключи ищем ОТ ПРОТИВНОГО, только ASCII-классами. Первая версия этой самой
#    проверки писала '^[[:alpha:]_]+:' — и была СЛЕПА к кириллице ровно так же, как
#    то, против чего написана: в системном grep без UTF-8-локали [[:alpha:]] русских
#    букв не берёт (замер: 0 совпадений против 1). Третий раз за сутки один класс
#    подводит внутри проверки, написанной о нём же.
MIXED=$(grep -E '^[^[:space:]#][^:]*:' config/lab.yaml.example \
        | grep -vE '^[a-zA-Z0-9_]+:' || true)
if [ -n "$MIXED" ]; then
  bad "в схеме настроек ключи РАЗНЫМИ алфавитами — обвязка писана под латиницу и кириллический ключ не увидит: $(printf '%s' "$MIXED" | tr '\n' ' ')"
else
  ok "ключи схемы одним алфавитом (латиница), комментарии русские — как и было заведено"
fi

# 8. НОМЕР ВЕРСИИ обязан двигаться вместе с содержимым каркаса.
#    03.09.2026: VERSION стоял на 1.0.1, а содержимое за один день изменилось
#    одиннадцатью правками. Отследить, что привезло очередное обновление, стало нечем:
#    у владельца и у автора «версия 1.0.1» — и это два разных каркаса. Номер, который
#    не двигается, хуже отсутствующего: отсутствующий честно молчит, а застывший
#    УТВЕРЖДАЕТ, что ничего не менялось.
#
# 🔴 ПЕРЕПИСАНО В ТОТ ЖЕ ДЕНЬ. Первая версия этой проверки прошла стенд из восьми
#    случаев и была неверна по существу — встречная проверка шестью независимыми
#    направлениями подтвердила 32 находки, сводящиеся к восьми корням. Каждый корень
#    ниже помечен в коде, чтобы следующая правка их не потеряла.
#
#    ① КАСАНИЕ ≠ ДВИЖЕНИЕ. Первая версия искала «последний коммит, ТРОГАВШИЙ файл
#      VERSION», а само ЗНАЧЕНИЕ номера не читала нигде. Поэтому зеленели: откат
#      номера назад (9.9.9 → 9.9.10 → 9.9.9), лишняя пустая строка в файле, пустой
#      файл и мусор вместо номера. Формулировка при этом утверждала «после её СДВИГА
#      каркас не менялся» — сдвиг, которого проверка не измеряла.
#    ② ИММУНИТЕТ ЗА КАСАНИЕ. Любая правка VERSION в рабочей папке гасила проверку по
#      ВСЕМ остальным файлам: условие было «VERSION тронут», а не «номер вырос».
#    ③ НОВЫЕ ФАЙЛЫ НЕВИДИМЫ. `git diff` не показывает неотслеживаемое, а печаталось
#      «каркас не менялся». Новый файл каркаса перед раздачей проходил насквозь.
#    ④ ЧУЖОЙ РЕПОЗИТОРИЙ. Каркас, положенный внутрь другого репозитория, мерился по
#      ЧУЖОЙ истории: краснел на посторонних файлах и зеленел на своей старой версии.
#    ⑤ НЕЗАВЕРШЁННОЕ СЛИЯНИЕ. Конфликт после `git pull` — то есть ровно то состояние,
#      в котором владельцу и велено запускать проверку, — давал полное зелёное, а
#      вместо номера печатались маркеры конфликта.
#    ⑥ АРХИВ, ПРИТВОРИВШИЙСЯ РЕПОЗИТОРИЕМ. `START_HERE.command` при отсутствии
#      истории делает `git init` и один коммит. Честный отказ «истории нет» превращался
#      в зелёное: история есть, VERSION в ней есть, после него ничего. Улика стёрта
#      самим каркасом. Признак — отсутствие связи с общим репозиторием.
#    ⑦ ПУТАЛИСЬ ДВА ЧИТАТЕЛЯ. Правки владельца шли в тот же ❌, что и недосмотр автора,
#      с советом «поднимите номер» — выполнив его, владелец получал зелёное над теми же
#      незащищёнными правками. А `ОБНОВЛЕНИЕ.md` посылал его жаловаться команде на
#      собственную правку. Теперь состояние ЭТОЙ машины — отдельный уровень ❗, не ошибка.
#    ⑧ МЕРИЛОСЬ ПО ЛОКАЛЬНОЙ ИСТОРИИ. Владелец, заведший свой координатор ровно по
#      инструкции каркаса и закоммитивший его, краснел НАВСЕГДА — и обвинялся автор.
#      Поэтому вопрос «двигался ли номер» задаётся ОБЩЕМУ каркасу (`origin/main`),
#      а не тому, что человек сделал у себя.
#
# ⛔ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Проверка обязана доказать, что СПОСОБНА увидеть движение
#    номера, — иначе «номер согласован» означает «сравнивать не умею». Контроль ниже:
#    в найденной правке значение номера обязано отличаться от родительского.
V_RE='^[0-9][0-9]*(\.[0-9][0-9]*)*$'
GITDIR=$(git rev-parse --git-dir 2>/dev/null || true)
PUB=""
if [ -n "$GITDIR" ]; then
  for r in origin/main origin/master origin/HEAD; do
    if git rev-parse --verify -q "$r" >/dev/null 2>&1; then PUB="$r"; break; fi
  done
fi

if ! command -v git >/dev/null 2>&1; then
  skip "версия: git не найден — сверить номер с содержимым нечем"
elif [ -z "$GITDIR" ] && [ -e .git ]; then
  skip "версия: git отказался читать историю в этой папке. Обычно это чужой владелец папки — попробуйте: git config --global --add safe.directory \"\$PWD\""
elif [ -z "$GITDIR" ]; then
  skip "версия: каркас взят без истории (это не репозиторий) — сверить номер с содержимым нечем"
elif [ "$(cd "$(git rev-parse --show-toplevel 2>/dev/null)" 2>/dev/null && pwd -P)" != "$(pwd -P)" ]; then
  # ⚠️ Сравнивать надо РАЗЫМЁНОВАННЫЕ пути. Первая версия сверяла с $PWD, и на macOS
  #    любая папка за символической ссылкой (/tmp, /var, iCloud, Dropbox) давала
  #    ложное «каркас в чужом репозитории»: git отвечает /private/var/…, а оболочка
  #    /var/…. Стенд упёрся в это ВСЕМИ шестнадцатью случаями сразу, и один из них
  #    при этом «прошёл» — зелёное не за то, ради чего писалось.
  skip "версия: каркас лежит ВНУТРИ другого репозитория — своей истории у него нет, мерить пришлось бы чужую"
elif [ -f "$GITDIR/shallow" ] || [ "$(git rev-parse --is-shallow-repository 2>/dev/null || echo true)" != "false" ]; then
  skip "версия: история обрезана (неглубокий клон) — за какой правкой стоит номер, отсюда не видно"
elif [ -e "$GITDIR/MERGE_HEAD" ] || [ -n "$(git ls-files -u 2>/dev/null)" ]; then
  skip "версия: слияние не завершено — доведите git pull до конца, потом запустите проверку снова"
elif [ -z "$PUB" ]; then
  skip "версия: у каркаса нет связи с общим репозиторием — историю, похоже, завели на месте, а не взяли командой git clone. Сверить номер с авторским не с чем"
elif [ ! -f VERSION ]; then
  skip "версия: нет файла VERSION — сравнивать не с чем"
else
  NOW=$(tr -d '[:space:]' < VERSION)
  # ① значение обязано БЫТЬ и обязано быть номером — иначе сравнивать нечего
  if [ -z "$NOW" ]; then
    skip "версия: файл VERSION пуст — номера нет"
  elif ! printf '%s' "$NOW" | grep -qE "$V_RE"; then
    skip "версия: в VERSION не номер, а «$(printf '%s' "$NOW" | cut -c1-40)» — сравнивать нечем"
  else
    # ① и ⑧ Ищем в ОБЩЕМ каркасе последнюю правку, где ЗНАЧЕНИЕ номера изменилось,
    #      а не просто попал файл. Иначе откат номера и правка пробелом гасят проверку.
    VCOMMIT=""; VVAL=""; VPREV=""
    for c in $(git log --format=%H -- VERSION 2>/dev/null | head -40); do
      git merge-base --is-ancestor "$c" "$PUB" 2>/dev/null || continue
      cur=$(git show "$c:VERSION" 2>/dev/null | tr -d '[:space:]')
      if git rev-parse --verify -q "$c^" >/dev/null 2>&1; then
        prv=$(git show "$c^:VERSION" 2>/dev/null | tr -d '[:space:]')
      else
        prv=""
      fi
      if [ "$cur" != "$prv" ]; then VCOMMIT="$c"; VVAL="$cur"; VPREV="$prv"; break; fi
    done
    if [ -z "$VCOMMIT" ]; then
      skip "версия: в общем каркасе не нашлось правки, где номер менялся, — сравнивать не с чем"
    elif [ -z "$VVAL" ]; then
      skip "версия: в найденной правке номер пуст — вердикт по версии недействителен"
    else
      # ⛔ контроль: значение в найденной правке обязано отличаться от родительского
      if [ "$VVAL" = "$VPREV" ]; then
        skip "версия: сравнение значений НЕ ВИДИТ заведомого различия — вердикт по версии недействителен"
      else
        AFTER=$(git -c core.quotepath=false diff --name-only "$VCOMMIT" "$PUB" 2>/dev/null | grep -v '^VERSION$' || true)
        # ③ неотслеживаемое тоже содержимое. --exclude-standard уважает .gitignore,
        #    поэтому личное владельца (notes/, work/, INBOX/, lab.local.yaml) не попадёт.
        DIRTY=$( { git -c core.quotepath=false diff --name-only HEAD 2>/dev/null; \
                   git -c core.quotepath=false ls-files --others --exclude-standard 2>/dev/null; } \
                 | grep -v '^VERSION$' | sort -u || true)
        MINE=$(git rev-list --count "$PUB..HEAD" 2>/dev/null || echo 0)

        # ── ❌ КРАСНОЕ — только про ОБЩИЙ каркас, то есть про работу автора ──────
        if [ "$(printf '%s\n%s\n' "$VPREV" "$VVAL" | sort -V | tail -1)" != "$VVAL" ] && [ -n "$VPREV" ]; then
          bad "номер версии поехал НАЗАД: $VPREV → $VVAL (правка $(printf '%.7s' "$VCOMMIT")). Под одним номером теперь ходят два разных каркаса — ровно то, против чего эта проверка."
        elif [ -n "$AFTER" ]; then
          N=$(printf '%s\n' "$AFTER" | grep -c . || true)
          bad "номер $VVAL стоит на месте, а содержимое общего каркаса с тех пор менялось ($N файлов) — по номеру нельзя понять, что привезло обновление:"
          printf '%s\n' "$AFTER" | head -8 | sed 's/^/       /'
          [ "$N" -gt 8 ] && echo "       … и ещё $((N-8))"
        else
          ok "номер $VVAL и содержимое общего каркаса согласованы"
        fi

        # ── ❗ ОТДЕЛЬНО: состояние ЭТОЙ машины. Не ошибка сборки. ───────────────
        # ⑦ Владелец, поправивший файл каркаса, не должен получать «противоречие»
        #    и идти жаловаться команде на собственную правку.
        if [ -n "$DIRTY" ]; then
          M=$(printf '%s\n' "$DIRTY" | grep -c . || true)
          if [ "$NOW" != "$VVAL" ] \
             && [ "$(printf '%s\n%s\n' "$VVAL" "$NOW" | sort -V | tail -1)" = "$NOW" ]; then
            warn "на этой машине изменено файлов каркаса: $M, номер поднят до $NOW и ещё не сохранён в историю — перед раздачей закоммитьте и запушьте"
          else
            warn "на этой машине изменено файлов каркаса: $M, номер при этом $NOW. Если правки ваши — они не пропадут, но следующее обновление остановится на конфликте, пока вы их не сохраните отдельно (см. ОБНОВЛЕНИЕ.md). VERSION владельцу трогать не нужно:"
            printf '%s\n' "$DIRTY" | head -8 | sed 's/^/       /'
            [ "$M" -gt 8 ] && echo "       … и ещё $((M-8))"
          fi
        fi
        # ⑧ свои правки, уже уложенные в историю, — тоже про эту машину, не про автора
        if [ "$MINE" -gt 0 ] 2>/dev/null; then
          warn "на этой машине своих правок сверх общего каркаса: $MINE. Это нормально, но вердикт по номеру вынесен по ОБЩЕМУ каркасу ($PUB), а не по ним"
        fi
      fi
    fi
  fi
fi

echo
# Вердикт называет ОБЪЁМ, а не только исход: «противоречий не найдено» на трёх
# выполненных проверках и на восьми читается одинаково успокоительно, пока число
# не напечатано рядом. Зелёного после пропуска не бывает — см. skip() выше.
# И три уровня различаются НАЗЫВАЯ АДРЕСАТА: ❌ — команде Арджуны (ошибка сборки),
# ❗ — тому, кто за этой клавиатурой (состояние его машины), ⚠️ — никому, потому что
# проверить не удалось и утверждать нечего.
SUM="выполнено проверок: $RAN"
[ "$WARN" -gt 0 ] && SUM="$SUM · замечаний по этой машине: $WARN"
[ "$SKIPPED" -gt 0 ] && SUM="$SUM · не удалось проверить: $SKIPPED"
if [ "$FAIL" -eq 0 ] && [ "$SKIPPED" -eq 0 ]; then
  if [ "$WARN" -eq 0 ]; then
    echo "✅ Противоречий не найдено ($SUM)."
  else
    echo "✅ Противоречий в каркасе не найдено ($SUM)."
    echo "   Строки ❗ — не ошибка сборки: это состояние вашей папки, чинить в каркасе нечего."
  fi
elif [ "$FAIL" -eq 0 ]; then
  echo "⚠️  Противоречий не найдено, НО часть проверок выполнить не удалось ($SUM)."
  echo "    Это НЕ зелёный вердикт: непроверенное и исправное отсюда неразличимы."
  exit 2
else
  echo "❌ Противоречий: $FAIL ($SUM)."
  echo "   Это ошибка сборки каркаса — скажите команде Арджуны, чинить вам не нужно."
fi
exit "$FAIL"
