#!/usr/bin/env bash
# Проверка согласованности каркаса — запускать после обновления и перед раздачей.
#
# ЗАЧЕМ. 01.09.2026 в каркасе нашли два противоречия, прожившие с первого дня:
#   • документы велели владельцу писать настройки в `config/lab.yaml`, а помощник читал
#     `config/lab.local.yaml` — имена уходили туда, где их никто не читает, и стирались
#     при первом же обновлении;
#   • `ОБНОВЛЕНИЕ.md` запрещал править `coordinators/`, а `docs/АРХИТЕКТУРА.md` велел
#     копировать туда шаблон — то есть ровно то, ради чего каркас и отдают.
#
# Оба появились не от небрежности: правка v1.0.1 переименовала файл в КОДЕ и не дошла до
# документов. Человек этого не увидит — файлы разные, каждый по отдельности верен.
# Поэтому проверка машинная и стоит НА ПУТИ обновления, а не в чьей-то памяти.
#
# Коды: 0 согласовано · 1 противоречие · 2 не смог проверить (файлов нет)

set -u
cd "$(dirname "$0")/.." || exit 2
FAIL=0
ok()   { echo "  ✅ $1"; }
bad()  { echo "  ❌ $1"; FAIL=$((FAIL+1)); }

# ⛔ САМОКОНТРОЛЬ ПЕРЕД ЛЮБЫМ ВЫВОДОМ. Системный grep на macOS БЕЗ UTF-8-локали не
#    сворачивает кириллический регистр: `grep -i 'впиши'` НЕ находит «Впишите» (проверено
#    01.09: 0 совпадений без локали, 1 — с LC_ALL). Первая версия этой проверки на том и
#    ослепла: контроль «документ велит писать в обновляемый файл» молча не сработал.
#    Поэтому ниже везде ЯВНЫЕ классы вида [Вв], а не -i, — они не зависят от окружения
#    того, кто запускает. А эта проба ловит случай, если инструмент сломан как-то иначе.
if [ "$(printf 'Впишите\n' | grep -c '[Вв]пиши')" != "1" ]; then
  echo "❌ проверка СЛЕПА на кириллице (grep не нашёл заведомое) — вердикт недействителен"
  exit 2
fi

echo "=== Согласованность каркаса ==="

for f in CLAUDE.md .gitignore ОБНОВЛЕНИЕ.md docs/АРХИТЕКТУРА.md ДОБРО_ПОЖАЛОВАТЬ.md; do
  [ -f "$f" ] || { echo "  ⚠️  нет $f — проверять нечего"; exit 2; }
done

# 1. Файл, который ЧИТАЕТ помощник, обязан быть тем, который ЗАЩИЩАЕТ .gitignore.
#    Иначе настройки владельца либо не читаются, либо затираются обновлением.
READS=$(grep -o 'config/lab[a-z.]*\.yaml' CLAUDE.md | sort -u | head -1)
IGNORED=$(grep -o 'config/lab[a-z.]*\.yaml' .gitignore | sort -u | head -1)
if [ -z "$READS" ] || [ -z "$IGNORED" ]; then
  bad "не нашёл, какой конфиг читает помощник ($READS) или что защищает .gitignore ($IGNORED)"
elif [ "$READS" = "$IGNORED" ]; then
  ok "помощник читает $READS — и он же под защитой .gitignore"
else
  bad "помощник читает $READS, а .gitignore защищает $IGNORED — настройки владельца потеряются"
fi

# 2. Ни один документ не должен ВЕЛЕТЬ владельцу писать в файл, который обновляется.
#    Упоминание в пояснении («это заготовка, она обновляется») законно — ищем ПОВЕЛЕНИЕ.
TRACKED_CFG="config/lab.yaml"
VELIT=$(grep -rn "$TRACKED_CFG" --include='*.md' . 2>/dev/null \
        | grep -vE '[Зз]аготовк|[Оо]бновля|[Пп]ерезапис|не ваш|была неправа|стояло|НЕ в |а НЕ' \
        | grep -E '[Вв]пиши|[Зз]апиши|[Уу]каж[ие]|[Зз]аполни|[Вв]неси|ваши настройки|ваши имена' || true)
if [ -z "$VELIT" ]; then
  ok "ни один документ не велит писать в $TRACKED_CFG"
else
  bad "документ велит писать в обновляемый $TRACKED_CFG:"
  printf '%s\n' "$VELIT" | sed 's/^/       /'
fi

# 3. Про coordinators/ документы не должны говорить противоположное.
#    Ищем прямой запрет рядом с прямым указанием копировать шаблон.
# ⚠️ Цитата запрета в ПОЯСНЕНИИ — не запрет. Первая версия этой проверки покраснела на
#    собственном примечании «до 01.09 здесь стояло „не правьте“»: упоминание засчиталось
#    за употребление. Отсекаем цитаты (строки-выноски `>`) и ссылки на прошлое.
ZAPRET=$(grep -rn 'coordinators/' --include='*.md' . 2>/dev/null \
         | grep -E 'не правьте|не трогайте|нельзя править' \
         | grep -vE ':[0-9]+:>' \
         | grep -vE 'стояло|[Рр]аньше|до 01\.09|была неправа|[Пп]режде' || true)
VELENIE=$(grep -rn 'coordinators/_template' --include='*.md' . 2>/dev/null || true)
if [ -n "$ZAPRET" ] && [ -n "$VELENIE" ]; then
  bad "один документ запрещает править coordinators/, другой велит копировать туда шаблон:"
  printf '%s\n' "$ZAPRET"   | sed 's/^/       запрет:  /'
  printf '%s\n' "$VELENIE" | sed 's/^/       указание:/'
else
  ok "про coordinators/ документы не спорят"
fi

# 4. START_HERE обязан открыть разговор ПЕРВЫМ ходом.
#    Голое `exec claude` даёт пустой REPL, который молчит, — при том что человеку строкой
#    выше обещано «помощник представится и задаст вопросы» (найдено 01.09).
if grep -qE '^[[:space:]]*exec[[:space:]]+claude[[:space:]]*$' START_HERE.command; then
  bad "START_HERE открывает ПУСТОЙ разговор (голое 'exec claude') — помощник промолчит, хотя владельцу обещано, что он представится и задаст вопросы"
elif grep -qE '^[[:space:]]*exec[[:space:]]+claude[[:space:]]+' START_HERE.command; then
  ok "START_HERE передаёт первый запрос — разговор начинает помощник"
else
  bad "в START_HERE не найден запуск claude — проверить вручную"
fi

# 5. Наработки: если про них СПРАШИВАЮТ, им должно быть КУДА лечь и КТО их читает.
#    До 01.09 онбординг спрашивал «что уже есть на руках», а ответ никуда не сохранялся:
#    лаборатория заводилась с чистого листа у человека, у которого лист не чистый.
ASKS=$(grep -c '[Нн]аработк' CLAUDE.md || true)
HAS_FIELD=$(grep -c '^наработки:' config/lab.yaml.example || true)
if [ "$ASKS" = "0" ]; then
  bad "онбординг не спрашивает про существующие наработки — владелец начнёт с нуля"
elif [ "$HAS_FIELD" = "0" ]; then
  bad "про наработки спрашивают, но в config/lab.yaml.example нет поля 'наработки' — ответ пропадёт"
else
  ok "наработки: спрашиваются, есть поле в конфиге, помощник читает их при старте"
fi

# 6. Схема настроек должна быть ОДНА. Два одинаковых шаблона под разными именами —
#    это развилка, из которой вырос исходный дефект каркаса: документы показывали на
#    один файл, помощник читал другой. До 01.09 lab.yaml и lab.yaml.example были
#    побайтно равны (1472 б); теперь lab.yaml — заглушка-пояснение, а схема одна.
if [ -f config/lab.yaml ] && [ -f config/lab.yaml.example ] \
   && cmp -s config/lab.yaml config/lab.yaml.example; then
  bad "config/lab.yaml и config/lab.yaml.example ПОБАЙТНО ОДИНАКОВЫ — две схемы под разными именами, из этой развилки уже вырастал дефект"
else
  ok "схема настроек одна (lab.yaml.example); lab.yaml — только путь переноса со старой версии"
fi

echo
if [ "$FAIL" -eq 0 ]; then
  echo "✅ Противоречий не найдено."
else
  echo "❌ Противоречий: $FAIL. Каркас в таком виде запутает владельца — почините до раздачи."
fi
exit "$FAIL"
